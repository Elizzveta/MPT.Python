# 10. Дан кортеж чисел с повторами. Получите кортеж из тех же чисел без повторов, отсортированный по возрастанию.

cort_10 = (3, 1, 4, 1, 5, 9, 2, 6, 5, 3, 5)
cort_10_unique = tuple(sorted(set(cort_10)))

