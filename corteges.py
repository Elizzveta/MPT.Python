# 1. Создайте кортеж из пяти чисел. Выведите его первый, последний и средний элементы.

cort_1 = (10, 20, 30, 40, 50)
print(f"Кортеж: {cort_1}")
print(f"Первый:", cort_1[0])
print(f"Последний:", cort_1[-1])
print(f"Средний:", cort_1[len(cort_1) // 2])

# 2. Из кортежа из восьми чисел получите: первые два элемента, последние два, кортеж в обратном порядке.

cort_2 = (1, 2, 3, 4, 5, 6, 7, 8)
print(f"Кортеж: {cort_2}")
print(f"Первые два: {cort_2[:2]}")
print(f"Последние два: {cort_2[-2:]}")
print(f"В обратном порядке: {cort_2[::-1]}")

