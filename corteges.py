# 4. Дан кортеж и число x. Выведите, есть ли x в кортеже, сколько раз оно встречается и индекс первого вхождения.

cort_4 = (4, 8, 15, 8, 23, 8, 42)
x = 8

print(f"Кортеж: {cort_4}")
