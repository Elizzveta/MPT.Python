# 2. Выведите элемент, стоящий в середине списка. Для списка чётной длины выведите оба средних.

list_2 = input("Введите элементы списка через пробел: ").split()

lenght = len(list_2)

if lenght==0:
    print("Список пуст")
elif lenght % 2 != 0:
    middle = list_2[lenght//2]
    print(f"Средний элемент: {middle}")
else:
    middle_1 = list_2[(lenght//2)-1]
    middle_2 = list_2[lenght//2]
    print(f"Средние элементы: {middle_1},{middle_2}")

